/// Upper bound on the clipboard backup taken before a pasteboard injection.
/// Generous because it covers images: a screenshot on the clipboard carries
/// PNG and uncompressed TIFF flavours side by side. Past it the clipboard is
/// left holding the dictated text rather than holding a huge copy in memory.
#[cfg(target_os = "macos")]
const PASTEBOARD_BACKUP_MAX_BYTES: usize = 256 * 1024 * 1024;

/// nspasteboard.org markers asking clipboard managers (Maccy, Alfred, Paste,
/// Raycast, …) not to record the dictated text: it is a vehicle for one paste,
/// not something the user copied.
#[cfg(target_os = "macos")]
const PASTEBOARD_TRANSIENT_MARKERS: [&str; 3] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
];

/// Typing posts each chunk as the Space key. Keyboard events carry their text
/// as a Unicode string, but input methods may ignore that string and
/// translate the keycode instead (Rime does whenever the text does not start
/// with ASCII): keycode 0, which enigo uses, is the A key and came out as
/// stray "a"s. A Space with no composition in progress is passed through, so
/// the application inserts the string; terminals, which decide by keycode
/// whether a key is text or a function key, still see a printable key.
#[cfg(target_os = "macos")]
const MACOS_SPACE_KEYCODE: u16 = 49;

/// `CGEventKeyboardSetUnicodeString` truncates the string it is given to 20
/// UTF-16 code units (undocumented; enigo and espanso both work around it).
#[cfg(target_os = "macos")]
const UNICODE_EVENT_MAX_UTF16_UNITS: usize = 20;

/// How long each typed chunk is given to be processed before the event source
/// is released; events still pending when it is released are dropped. The
/// same budget enigo applies, so typing finishes on the same schedule.
#[cfg(target_os = "macos")]
const UNICODE_EVENT_SETTLE_MS: u64 = 20;

